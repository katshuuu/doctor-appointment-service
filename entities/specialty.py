"""Сущность «Специальность».

Специальность врача представлена строкой и хранится как атрибут
Doctor.specialty. Модуль лишь фиксирует справочник специальностей,
доступных в сервисе, отдельно от структуры врача.
"""

KNOWN_SPECIALTIES: tuple[str, ...] = (
    "Терапевт",
    "Кардиолог",
    "Невролог",
    "Педиатр",
    "Хирург",
    "Офтальмолог",
    "Стоматолог",
    "Дерматолог",
    "Уролог",
    "Эндокринолог",
    "Оториноларинголог",
    "Гинеколог",
    "Психиатр",
    "Аллерголог",
    "Онколог",
)


def is_known_specialty(specialty: str) -> bool:
    """Проверить, входит ли специальность в справочник известных."""
    return specialty in KNOWN_SPECIALTIES
